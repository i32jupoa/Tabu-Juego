/**
 * Mazo local ampliado y curado. Las cinco categorías grandes ya cuentan con
 * 300 cartas específicas cada una; se combinan con las cartas históricas de
 * Personajes/Naturaleza y cualquier carta base que no esté duplicada.
 * La clave de deduplicación es categoría + palabra objetivo.
 */
const CURATED_CATEGORY_CARDS: TabuCard[] = [
  ...GENERAL_CARDS,
  ...DEPORTES_CARDS,
  ...CINE_CARDS,
  ...TECNOLOGIA_CARDS,
  ...COMIDA_CARDS,
];

const dedupeCards = (cards: TabuCard[]): TabuCard[] => {
  const seen = new Set<string>();
  return cards.filter((card) => {
    const key = `${card.category}:${card.word.trim().toLocaleLowerCase("es")}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
};

export const CARDS: TabuCard[] = dedupeCards([...CURATED_CATEGORY_CARDS, ...BASE_CARDS]);
